from docx.shared import Pt
from docx.enum.text import WD_PARAGRAPH_ALIGNMENT


def add_heading(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    return p


def add_para(doc, text, bold=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    return p


